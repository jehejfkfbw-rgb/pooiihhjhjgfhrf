let seedingPromise: Promise<void> | null = null;

async function countOf(table: any) {
  const [{ count }] = await db.select({ count: sql<number>`count(*)::int` }).from(table);
  return count;
}

/** بيتأكد إن كل جدول اتبذر (كل واحد مستقل) */
export function ensureSeeded(): Promise<void> {
  if (!seedingPromise) {
    seedingPromise = (async () => {
      try {
        // الإعدادات: ضيف المفاتيح الناقصة بس
        const existingKeys = new Set((await db.select().from(settings)).map((r) => r.key));
        const missing = Object.entries(DEFAULT_SETTINGS)
          .filter(([k]) => !existingKeys.has(k))
          .map(([key, value]) => ({ key, value }));
        if (missing.length) await db.insert(settings).values(missing);

        if ((await countOf(aiDevs)) === 0) await db.insert(aiDevs).values(DEVS);
        if ((await countOf(staff)) === 0) await db.insert(staff).values(STAFF);
        if ((await countOf(securityAgents)) === 0) await db.insert(securityAgents).values(SECURITY_AGENTS);
        if ((await countOf(projects)) === 0) await db.insert(projects).values(PROJECTS);
        if ((await countOf(services)) === 0) await db.insert(services).values(SERVICES);
        if ((await countOf(knowledge)) === 0) await db.insert(knowledge).values(KNOWLEDGE);

        // ردود الطلبات بتتضاف حتى لو القاعدة القديمة موجودة
        const [{ count: orderKb }] = await db
          .select({ count: sql<number>`count(*)::int` })
          .from(knowledge)
          .where(sql`category = 'الطلبات'`);
        if (orderKb === 0) await db.insert(knowledge).values(KNOWLEDGE_ORDERS);

        console.log("[NOVA] Core verified: settings/devs/staff/security/projects/services/knowledge");
      } catch (err) {
        seedingPromise = null;
        console.error("[NOVA] seeding failed:", err);
      }
    })();
  }
  return seedingPromise;
}

/** قراءة كل الإعدادات ككائن */
export async function getSettings(): Promise<Record<string, string>> {
  await ensureSeeded();
  const rows = await db.select().from(settings);
  const map: Record<string, string> = {};
  for (const r of rows) map[r.key] = r.value;
  return { ...DEFAULT_SETTINGS, ...map };
}
